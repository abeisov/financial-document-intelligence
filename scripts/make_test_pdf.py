H2 = ParagraphStyle("H2", fontName="Doc-Bold", fontSize=12, leading=16, spaceBefore=8, spaceAfter=6)
BODY = ParagraphStyle("BODY", fontName="Doc", fontSize=9.5, leading=14, spaceAfter=5)

TABLE_STYLE = TableStyle(
    [
        ("FONTNAME", (0, 0), (-1, -1), "Doc"),
        ("FONTNAME", (0, 0), (-1, 0), "Doc-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8EDF2")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#9AA7B4")),
        ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]
)


def table(rows: list[list[str]], widths: list[float]) -> Table:
    t = Table(rows, colWidths=widths, hAlign="LEFT")
    t.setStyle(TABLE_STYLE)
    return t


