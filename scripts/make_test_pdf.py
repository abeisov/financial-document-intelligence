        Paragraph("Страница 3 — бухгалтерский баланс и долговая позиция.", BODY),
        Paragraph("Страница 4 — отчёт о движении денежных средств.", BODY),
        Paragraph("Страница 5 — примечания, ковенанты и расчётные коэффициенты.", BODY),
